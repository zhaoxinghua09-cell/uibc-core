#!/usr/bin/env python3
"""Build a single-file, stdlib-only verifier that can be embedded in a package.

`uibc submit --embed-verifier <script>` copies a script into the package as
`verify/uibc_verify.py` and binds its hash in the manifest (check S1 enforces
it). This produces that script from the second implementation, so a package can
be checked with nothing but Python - no clone, no pip install, no network.

    python tools/build_standalone_verifier.py            # -> build/uibc_verify.py
    python tools/build_standalone_verifier.py --out X.py

The emitted file carries `independent_verifier/iverify.py` verbatim plus a small
`main()` that prints what `verify` prints: JSON with `result` and `checks`.

Honest labels travel with it: this is a second implementation by the same
maintainer, not an audit, and its check ids are V1-V9 - a deliberately different
vocabulary from the reference verifier's S1-S18, because the two were written
from the spec independently and agreement between them is the signal.
"""
from __future__ import annotations

import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
SRC = os.path.join(REPO, "independent_verifier", "iverify.py")
DEFAULT_OUT = os.path.join(REPO, "build", "uibc_verify.py")

SHIM = r'''

# --- standalone entry point (appended by tools/build_standalone_verifier.py) ---

def _standalone_main(argv=None):
    import json as _json
    import sys as _sys

    argv = list(_sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ("-h", "--help"):
        print("usage: uibc_verify.py <package-dir>\n"
              "Prints JSON: {result, checks:[{id,result}]}. Exit 0 = PASS, "
              "1 = FAIL, 2 = INCONCLUSIVE.")
        return 0 if argv else 2

    report = independent_verify(argv[0])
    checks = [{"id": k, "result": v} for k, v in sorted(report["checks"].items())]
    out = {"result": report["result"], "checks": checks,
           "implementation": "iverify (second implementation, same maintainer)",
           "check_vocabulary": "V1-V9"}
    print(_json.dumps(out, ensure_ascii=False, indent=2))
    return {"PASS": 0, "FAIL": 1}.get(report["result"], 2)


if __name__ == "__main__":
    import sys as _sys
    _sys.exit(_standalone_main())
'''


def main() -> int:
    out = DEFAULT_OUT
    if "--out" in sys.argv:
        out = os.path.abspath(sys.argv[sys.argv.index("--out") + 1])

    with io.open(SRC, "r", encoding="utf-8") as f:
        body = f.read()

    banner = ("#!/usr/bin/env python3\n"
              '"""Standalone UIBC verifier - stdlib only, no repository needed.\n\n'
              "Generated by tools/build_standalone_verifier.py from\n"
              "independent_verifier/iverify.py. Second implementation by the\n"
              "maintainer of uibc_core, written from the spec; not an audit.\n"
              '"""\n')
    text = banner + body + SHIM

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with io.open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (out, len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
