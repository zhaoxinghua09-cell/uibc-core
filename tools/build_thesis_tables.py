#!/usr/bin/env python3
"""The tables a thesis chapter 5 would need, assembled from measurements.

Nothing here is typed by hand. Each table reads the same JSON the tools emit,
so a chapter that cites these numbers cites numbers that can be regenerated by
a reader with one command per table. That is the whole reason to generate the
chapter from code rather than write it once and let it drift.

Numbering follows GB/T 7713.2 chapter-table conventions: 表 5-1, 表 5-2, ...
with the caption above the table and the source note below it.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TOOLS = os.path.join(_REPO, "tools")
for p in (_REPO, TOOLS):
    if p not in sys.path:
        sys.path.insert(0, p)

from uibc_core import basis  # noqa: E402

DOCS = os.path.join(_REPO, "docs")


def run(tool, *args):
    proc = subprocess.run([sys.executable, os.path.join(TOOLS, tool), *args],
                          capture_output=True, text=True, cwd=_REPO, timeout=900)
    if proc.returncode != 0:
        raise SystemExit("%s failed: %s" % (tool, proc.stderr[-300:]))
    return proc.stdout


def run_json(tool):
    return json.loads(run(tool, "--json"))


def parity():
    return run_json("check_release_parity.py")


def diagnostics():
    return run_json("compare_diagnostics.py")


def matrix():
    return run_json("check_matrix.py")


def facts():
    with open(os.path.join(DOCS, "COMPETITOR-FACTS.json"), encoding="utf-8") as f:
        return json.load(f)


def latency():
    """Read the measured hot-path figure out of the doc that reports it, and
    refuse to print a placeholder if it is missing."""
    path = os.path.join(DOCS, "LIVE-INTEGRATION.md")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"median\s*\|?\s*\*\*([0-9.]+)\s*ms\*\*", text)
    p99 = re.search(r"p99\s*\|\s*([0-9.]+)\s*ms", text)
    if not m:
        raise SystemExit("LIVE-INTEGRATION.md no longer reports a median latency")
    return {"median": m.group(1), "p99": p99.group(1) if p99 else None}


# ---------------------------------------------------------------- tables

def t51():
    rows = []
    for cid in sorted(basis.BASIS, key=lambda s: int(s[1:]) if s[1:].isdigit() else 99):
        b = basis.for_check(cid)
        cite = b["citation"] or "—"
        rows.append((cid, b["note"].split(";")[0].strip(), basis.CLASS_LABEL[b["class"]], cite))
    return rows


def build():
    par = parity()
    dg = diagnostics()
    mx = matrix()
    f = facts()
    lat = latency()
    bc = basis.counts()
    return {"parity": par, "diag": dg, "matrix": mx, "facts": f, "lat": lat,
            "basis": bc, "checks": t51()}


def md(d):
    out = ["# 第 5 章 实证：可直接引用的表格", "",
           "**生成方式**：`python3 tools/build_thesis_tables.py`。表中每个数字都来自"
           "同仓库脚本的 JSON 输出，读者可用表下注明的命令重跑；本文件不手工维护数字。", ""]

    # 表 5-1
    out += ["## 表 5-1　检查项及其依据分类", "",
            "| 编号 | 检查内容 | 依据类别 | 依据文本 |", "|---|---|---|---|"]
    for cid, note, cls, cite in d["checks"]:
        out.append("| %s | %s | %s | %s |" % (cid, note, cls, cite))
    out += ["", "注：依据类别按「草案或 RFC 明文规定」「思想来源」「本项目自定」三分；"
            "标为本项目自定的四项，其 citation 字段为空字符串，论文中不得补写条款号。",
            "数据来源：`python3 -c \"from uibc_core import basis; basis.for_check('S1')\"`。", ""]

    # 表 5-2
    bc = d["basis"]
    out += ["## 表 5-2　依据分布", "",
            "| 依据类别 | 项数 |", "|---|---|"]
    for k in ("direct", "related", "none"):
        out.append("| %s | %d |" % (basis.CLASS_LABEL[k], bc[k]))
    out.append("| 合计 | %d |" % sum(bc.values()))
    out += ["", "数据来源：`python3 -c \"from uibc_core import basis; print(basis.counts())\"`。", ""]

    # 表 5-3
    mx = d["matrix"]
    out += ["## 表 5-3　攻击—检查发生矩阵摘要", "",
            "| 指标 | 值 |", "|---|---|",
            "| 受测攻击数 | %d |" % mx["n_attacks"],
            "| 使至少一项检查 FAIL 的攻击数 | %d |" % mx["n_caught"],
            "| 仅使一项检查 FAIL 的攻击数 | %d |" % len(mx["isolated"]),
            "| 未被任何攻击触达的检查 | %s |" % ("、".join(mx["unreached"]) or "无"),
            "| 参与矩阵的检查项 | %d（不含 S0） |" % len(mx["checks"]), ""]
    out.append("注：S0 是异常兜底，不属于可被单独触发的检查项，故不进入矩阵；"
               "因此此处为 18 项，而表 5-5 的仓库渠道报 19 项（含 S0）。")
    multi = [r for r in mx["rows"] if r["n"] > 1]
    if multi:
        out += ["同时触发多项检查的攻击（耦合项，已在正文注明）：", "",
                "| 攻击 | 触发的检查 |", "|---|---|"]
        for r in multi:
            out.append("| %s | %s |" % (r["name"], "、".join(r["checks"])))
        out.append("")
    out += ["数据来源：`python3 tools/check_matrix.py --json`；逐格矩阵见 `docs/CHECK-MATRIX.md`。", ""]

    # 表 5-4
    dg = d["diag"]
    common = [c["attack"] for c in dg["ours"]["cases"]
              if any(t["attack"] == c["attack"] and t["verdict"] != "n/a"
                     for t in dg["theirs"]["cases"])]
    ours = sum(c["n_reasons"] for c in dg["ours"]["cases"] if c["attack"] in common)
    theirs = sum(c["n_reasons"] for c in dg["theirs"]["cases"] if c["attack"] in common)
    out += ["## 表 5-4　同等攻击下两实现的诊断输出比较", "",
            "| 项 | 本实现 | %s %s |" % (d["facts"]["subject"], d["facts"]["version"]),
            "|---|---|---|",
            "| 双方均可表达的破坏类别 | %d | %d |" % (len(common), len(common)),
            "| 报出的具体原因条数 | %d | %d |" % (ours, theirs),
            "| 原因可定位到具体文件 | 可以 | 否（定位到缺失字段） |",
            "| 每条原因附依据条款 | 结构化字段 + `uibc explain` | 句内联条款号 |", ""]
    out += ["注：条数差异源于粒度不同，不表示判定能力优劣；对方的单条原因覆盖整个 capsule，"
            "本实现的单条原因指向单个文件。",
            "数据来源：`python3 tools/compare_diagnostics.py --json`。", ""]

    # 表 5-5
    ch = d["parity"]["channels"]
    out += ["## 表 5-5　同一版本在三处发布渠道的检查覆盖", "",
            "| 渠道 | 版本 | 报出的检查项数 | 检查项 |", "|---|---|---|---|"]
    for name, v in ch.items():
        out.append("| %s | %s | %d | %s |" % (name, v.get("version", "—"),
                                               len(v["checks"]), "、".join(v["checks"])))
    out += ["", "注：差异源于发布未随仓库推进，非代码差异。",
            "数据来源：`python3 tools/check_release_parity.py --json`。", ""]

    # 表 5-6
    out += ["## 表 5-6　集成实测（单次工具调用热路径）", "",
            "| 指标 | 值 |", "|---|---|",
            "| 计量单位 | 一次 `record()`（含索引重写与证据文件写盘） |",
            "| 中位延迟 | %s ms |" % d["lat"]["median"],
            "| p99 | %s ms |" % (d["lat"]["p99"] or "—"), ""]
    out += ["注：该口径含写盘与索引重写，与只计校验的亚毫秒数字不可直接比较；"
            "正文按同量级表述，不宣称优势。",
            "数据来源：`python3 tools/latency_per_call.py --json`；口径说明见 `docs/LIVE-INTEGRATION.md`。", ""]

    out += ["## 未纳入本章的项（避免超范围陈述）", "",
            "- 外部第三方独立见证：本实现为 0；对方公开材料记录 %d 家第三方实现。"
            % d["facts"]["third_party_implementations"],
            "- 在线验证端点：本实现仅有本地端点，未部署。",
            "- macOS 平台与网络挂载场景未测。",
            "- 链尾收据正文不可由包内材料判定（见 `docs/CHECK-MATRIX.md` 中 `(not caught)` 一行）。", ""]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    d = build()
    if a.json:
        print(json.dumps({"matrix": d["matrix"], "basis": d["basis"],
                          "latency": d["lat"], "channels":
                          {k: len(v["checks"]) for k, v in d["parity"]["channels"].items()}},
                         ensure_ascii=False, indent=2))
    else:
        print(md(d))
