#!/usr/bin/env python3
"""Which attacks reach which checks.

The audit says 37 attacks pass. It does not say whether they are *distinct*
attacks: if every one of them lit up six checks at once, the suite would
over-report, and if one check were never reached by any attack, that check
would be untested decoration.

This reads the audit's own JSON and prints the incidence matrix, plus the two
numbers that matter:

* fan-out -- how many checks one attack moves. 1 means the attack isolates one
  fact; more means the facts are coupled and the paper should say so.
* reach   -- how many separate attacks reach one check. 0 means that check has
  never been shown to fire.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

_REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TOOLS = os.path.join(_REPO, "tools")

STAGES = ("stage_redteam", "stage_redteam_v11", "stage_redteam_ext",
          "stage_redteam_s16", "stage_redteam_ckpt", "stage_redteam_pinned")


def audit():
    proc = subprocess.run([sys.executable, os.path.join(TOOLS, "outsider_audit.py"),
                           "--json"], capture_output=True, text=True, cwd=_REPO,
                          timeout=900)
    if proc.returncode != 0 and not proc.stdout.strip():
        raise SystemExit("outsider_audit failed: %s" % proc.stderr[-400:])
    return json.loads(proc.stdout)


def cases(d):
    out = []
    for stage in STAGES:
        block = d.get(stage) or {}
        for row in block.get("rows", []):
            if row.get("kind") == "control":
                continue
            out.append({"stage": stage.replace("stage_", ""),
                        "name": row["name"],
                        "got": row.get("got"),
                        "checks": sorted(set(row.get("failed_checks") or []))})
    for gap in (d.get("stage_redteam_v11") or {}).get("known_gaps", []):
        if not gap.get("caught"):
            out.append({"stage": "known-gap", "name": gap["name"],
                        "got": "not caught", "checks": []})
    return out


def build(d):
    cs = cases(d)
    used = sorted({c for x in cs for c in x["checks"]},
                  key=lambda s: int(s[1:]) if s[1:].isdigit() else 99)
    rows = []
    for x in cs:
        rows.append(dict(x, n=len(x["checks"])))
    reach = {c: sum(1 for r in rows if c in r["checks"]) for c in used}
    isolated = [r["name"] for r in rows if r["n"] == 1]
    return {"checks": used, "rows": rows, "reach": reach,
            "isolated": isolated,
            "n_attacks": len(rows), "n_caught": sum(1 for r in rows if r["checks"]),
            "unreached": [c for c, n in reach.items() if n == 0]}


def render_md(d):
    checks = d["checks"]
    out = ["# Attack / check incidence", "",
           "Each column is a check; `x` means this attack made that check FAIL.",
           "A row with no marks and verdict PASS is a control: the correct input "
           "is supposed to pass.",
           "Generated by `tools/check_matrix.py` from `tools/outsider_audit.py --json`.", ""]
    out.append("| attack | " + " | ".join(checks) + " | n |")
    out.append("|---|" + "|".join(["---"] * len(checks)) + "|---|")
    for r in d["rows"]:
        cells = ["x" if c in r["checks"] else "" for c in checks]
        out.append("| %s | %s | %d |" % (r["name"], " | ".join(cells), r["n"]))
    out += ["", "## What the numbers say", "",
            "- **%d attacks, %d of which caught something.**" % (d["n_attacks"], d["n_caught"]),
            "- **%d attacks isolate exactly one check** (fan-out 1): %s." % (
                len(d["isolated"]), ", ".join(d["isolated"][:8]) +
                (" …" if len(d["isolated"]) > 8 else "")),
            "- **Checks never reached by any attack: %s.**" % (
                ", ".join(d["unreached"]) if d["unreached"] else "none"),
            "",
            "Fan-out above 1 is not a defect; a single edit can genuinely break "
            "several facts at once (a deleted file breaks its hash, its inclusion "
            "proof and its declared count). It is recorded so a claim of "
            "「each check tests one thing」 cannot be made loosely.", ""]
    out.append("## Reach per check")
    out.append("| check | attacks that reach it |")
    out.append("|---|---|")
    for c in checks:
        out.append("| %s | %d |" % (c, d["reach"][c]))
    return "\n".join(out) + "\n"



FONT = "Noto Sans CJK SC, Source Han Sans SC, Microsoft YaHei, PingFang SC, sans-serif"
INK = "#1a1a1a"
MUTED = "#6b6b6b"
HIT = "#1f5fa8"
HIT2 = "#b8532a"


def render_svg(d):
    checks = d["checks"]
    rows = d["rows"]
    left, top, rowh = 292, 132, 16
    cw = 46
    W = left + cw * len(checks) + 44
    H = top + rowh * len(rows) + 96
    o = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (W, H, W, H),
         '<rect width="%d" height="%d" fill="#fff"/>' % (W, H),
         '<text x="32" y="44" font-family="%s" font-size="24" fill="%s" font-weight="bold">'
         '每个攻击动了哪几项检查</text>' % (FONT, INK),
         '<text x="32" y="70" font-family="%s" font-size="12" fill="%s">'
         '%d 个攻击，%d 个只让一项失败；右侧红格是一项攻击同时动了多项的地方，如实标出</text>'
         % (FONT, MUTED, d["n_attacks"], len(d["isolated"]))]
    for i, c in enumerate(checks):
        o.append('<text x="%d" y="%d" font-family="%s" font-size="11" fill="%s" '
                 'text-anchor="middle">%s</text>'
                 % (left + cw * i + cw // 2, top - 10, FONT, MUTED, c))
    for r, row in enumerate(rows):
        y = top + r * rowh
        label = row["name"][:44]
        missed = False
        if not row["checks"]:
            if row["got"] == "PASS":
                label += "  (passes, as it should)"
            else:
                label += "  (not caught)"
                missed = True
        o.append('<text x="%d" y="%d" font-family="%s" font-size="10" fill="%s" '
                 'text-anchor="end">%s</text>'
                 % (left - 12, y + 11, FONT, HIT2 if missed else MUTED, label))
        for i, c in enumerate(checks):
            if c in row["checks"]:
                fill = HIT if row["n"] == 1 else HIT2
                o.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s" rx="2"/>'
                         % (left + cw * i + 4, y + 1, cw - 8, rowh - 4, fill))
    o.append('<text x="32" y="%d" font-family="%s" font-size="11" fill="%s">'
             '复跑：python3 tools/check_matrix.py   （数据源：outsider_audit.py --json）</text>'
             % (H - 24, FONT, MUTED))
    o.append("</svg>")
    return "\n".join(o)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--svg", action="store_true")
    a = ap.parse_args()
    d = build(audit())
    if a.json:
        print(json.dumps(d, ensure_ascii=False, indent=2))
    elif a.svg:
        print(render_svg(d))
    else:
        print(render_md(d))
